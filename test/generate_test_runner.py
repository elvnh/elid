import argparse
import re
import pathlib
import os.path

def error(msg):
    print(msg)
    exit(1)


def gather_test_cases_in_file(file_contents):
    regular_cases = re.findall(r'^TEST_CASE\((.*)\)', file_contents, flags=re.MULTILINE)
    repeat_cases = re.findall(r'^TEST_CASE_REPEAT\((.*),\s*(.*)\)', file_contents, flags=re.MULTILINE)

    return regular_cases + repeat_cases


def test_case_has_repeat_count(c):
    result = isinstance(c, tuple)
    return result

def gather_test_cases(files):
    result = []

    for filename in files:
        with open(filename, 'r') as f:
            cases_in_file = gather_test_cases_in_file(f.read())

            result += cases_in_file

            for c in cases_in_file:
                name = c

                if test_case_has_repeat_count(c):
                    name = c[0]

                if len(name) == 0:
                    error('Test case name cannot be empty. Stopping.')

    return result


PREAMBLE = """/* This file is generated by a script - do not modify it or add to source control! */

#include <stdint.h>
#include <stdlib.h>
#include <stddef.h>
#include <string.h>
#include <stdio.h>
#include <inttypes.h>

#include "base/base_all.cpp"
#include "proc/proc_all.cpp"
#include "scan/scan_all.cpp"
#include "app/app_all.cpp"

/* Testing macros */
#define REQUIRE(e)                \\
do {                              \\
    ++g_assertions_ran;           \\
    if (!(e)) {                   \\
        ON_REQUIRE_FAIL(#e);      \\
    } else {                      \\
        ++g_assertions_passed;    \\
    }                             \\
} while (0)

#define REQUIRE_STR_EQ(a, b) REQUIRE(str_eq((a), (b)))

#if defined(__GNUC__)
#    define TEST_DEBUG_BREAK() __builtin_trap()
#elif defined(_MSC_VER)
#    define TEST_DEBUG_BREAK() __debugbreak()
#endif

#define ON_REQUIRE_FAIL(str)                               \\
do {                                                       \\
     fprintf(stderr, "\\n*** TEST ASSERTION FAILED ***\\n"   \\
         "Expression: '%s'\\nTest case: %s\\n%s:%d:\\n\\n",     \\
         str, __func__, __FILE__, __LINE__);               \\
     switch (g_on_require_fail_behaviour) {                \\
         case ON_REQUIRE_FAIL_EXIT: {                      \\
             exit(1);                                      \\
         } break;                                          \\
                                                           \\
         case ON_REQUIRE_FAIL_BREAK: {                     \\
             TEST_DEBUG_BREAK();                           \\
         } break;                                          \\
                                                           \\
         case ON_REQUIRE_FAIL_CONTINUE: {                  \\
         } break;                                          \\
     }                                                     \\
} while (0)

#define TEST_CASE(name) static void TEST_CASE__##name(void)
#define TEST_CASE_REPEAT(name, count) TEST_CASE(name)

/* Test runner globals */
static uint64_t g_assertions_ran;
static uint64_t g_assertions_passed;

enum {
    ON_REQUIRE_FAIL_CONTINUE,
    ON_REQUIRE_FAIL_EXIT,
    ON_REQUIRE_FAIL_BREAK,
} g_on_require_fail_behaviour;

/* Test case globals */
Arena *test_arena;
"""

def generate_test_runner_source(filenames, cases, output_dir):
    includes = ''
    for f in filenames:
        relative = os.path.relpath(f, start=output_dir)
        includes += f'#include "{relative}"\n'

    calls = ''

    for c in cases:
        if test_case_has_repeat_count(c):
            name, count = c
            calls += f'    for (int i = 0; i < {count}; ++i) {{ TEST_CASE__{name}(); }}\n'
        else:
            calls += f'    TEST_CASE__{c}();\n'

    result = f"""{PREAMBLE}
{includes}

#define TOTAL_NUMBER_OF_TEST_CASES (uint64_t){len(cases)}

int main(int argc, char **argv)
{{
    test_arena = arena_create(MB(8));

    for (int i = 1; i < argc; ++i) {{
        if (strcmp(argv[i], "-b") == 0) {{
            g_on_require_fail_behaviour = ON_REQUIRE_FAIL_BREAK;
        }} else if (strcmp(argv[i], "-e") == 0) {{
            g_on_require_fail_behaviour = ON_REQUIRE_FAIL_EXIT;
        }} else if (strcmp(argv[i], "-c") == 0) {{
            g_on_require_fail_behaviour = ON_REQUIRE_FAIL_CONTINUE;
        }} else {{
            fprintf(stderr, "Unknown command line option '%s'. Stopping.\\n", argv[i]);
            exit(1);
        }}
    }}

{calls}

    printf("Passed %" PRIu64 "/%" PRIu64 " assertions in %" PRIu64 " test case%s.\\n",
        g_assertions_passed, g_assertions_ran, TOTAL_NUMBER_OF_TEST_CASES,
        (TOTAL_NUMBER_OF_TEST_CASES == 1) ? "" : "s");

    return 0;
}}
    """

    return result


def main():
    parser = argparse.ArgumentParser(prog='generate_test_runner')
    parser.add_argument('filenames', nargs='+')
    parser.add_argument('-o', '--output', required=True)
    parser.add_argument('-q', '--quiet', '--silent')

    args = parser.parse_args()

    output_path = pathlib.Path(args.output)
    abs_output_path = pathlib.Path(args.output).absolute()
    output_dir = abs_output_path.parent

    input_files = [f for f in args.filenames if pathlib.Path(f).absolute() != abs_output_path]

    cases = gather_test_cases(input_files)

    src = generate_test_runner_source(input_files, cases, output_dir)

    with open(abs_output_path, 'w') as f:
        f.write(src)

    if not args.quiet:
        print(f'Generated test runner \'{output_path}\' containing {len(cases)} test cases.')

if __name__ == '__main__':
    main()
